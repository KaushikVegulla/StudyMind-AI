"""Quiz / flashcard / summary generation.

Two modes, always labelled in the response:

- ``llm`` — generated by the configured LLM (Gemini / Groq) from the
  workspace's chunks only, parsed from the model's JSON/text output.
- ``extractive_scaffold`` — no LLM configured, or the LLM output could
  not be parsed or validated: summaries quote the opening chunks and
  flashcards/quiz items are built from key sentences. Never presented
  as LLM output.

Generated artifacts are cached in the repository (the generation
cache): one artifact per workspace/document, kind and count. A repeat
request returns the cached copy with ``"cached": true`` and makes no
LLM call, unless ``force`` is set — free-tier quota is the scarcest
resource this app has.

Quizzes are validated item by item (services/quiz_validation.py):
exactly 4 distinct options, one correct answer, and keywords shared
with the source chunks. If no item from an LLM response validates,
generation is retried once; if the retry also fails, the labelled
extractive scaffold is used.

Flashcards are persisted with SM-2 scheduling state
(services/srs.py) so they can be reviewed: ``GET
/generate/flashcards/due`` lists cards whose ``due_at`` has passed and
``POST /generate/flashcards/review`` records a grade.
"""
from __future__ import annotations

import json
import re

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, Field

from ..repositories import get_repository
from ..services import llm, quiz_validation, srs

router = APIRouter(prefix="/generate", tags=["generate"])


class GenerateIn(BaseModel):
    workspace_id: str
    count: int = 5
    document_id: str | None = None
    force: bool = False


class ReviewIn(BaseModel):
    flashcard_id: str
    grade: int = Field(ge=0, le=5)


def _chunks_for(body: GenerateIn) -> list[dict]:
    repo = get_repository()
    if not repo.get_workspace(body.workspace_id):
        raise HTTPException(404, "Workspace not found")
    chunks = repo.list_chunks(body.workspace_id)
    if body.document_id:
        if not any(d["id"] == body.document_id
                   for d in repo.list_documents(body.workspace_id)):
            raise HTTPException(404, "Document not found in this workspace")
        chunks = [c for c in chunks if c["document_id"] == body.document_id]
    if not chunks:
        raise HTTPException(400, "No material uploaded in this workspace yet")
    return sorted(chunks, key=lambda c: (c["page"], c["index"]))


def _cached(body: GenerateIn, kind: str) -> dict | None:
    if body.force:
        return None
    return get_repository().get_generated(
        body.workspace_id, body.document_id, kind, body.count)


def _store(body: GenerateIn, kind: str, payload: dict) -> dict:
    get_repository().save_generated(
        body.workspace_id, body.document_id, kind, body.count, payload)
    return {**payload, "cached": False}


def _context(chunks: list[dict], limit: int = 6000) -> str:
    return "\n\n".join(
        f"[{c.get('filename', '')} p.{c['page']}] {c['text']}" for c in chunks
    )[:limit]


def _parse_json(text: str | None):
    """Extract a JSON value from model output that may carry code fences
    or a short preamble. Returns None when nothing parses."""
    if not text:
        return None
    cleaned = text.strip()
    cleaned = re.sub(r"^```(?:json)?\s*|\s*```$", "", cleaned,
                     flags=re.IGNORECASE | re.MULTILINE).strip()
    for candidate in (cleaned, cleaned[cleaned.find("["):cleaned.rfind("]") + 1],
                      cleaned[cleaned.find("{"):cleaned.rfind("}") + 1]):
        if not candidate:
            continue
        try:
            return json.loads(candidate)
        except (ValueError, TypeError):
            continue
    return None


def _sentences(chunks: list[dict]) -> list[str]:
    text = " ".join(c["text"] for c in chunks)
    return [s.strip() for s in re.split(r"(?<=[.!?])\s+", text) if len(s.strip()) > 40]


@router.post("/summary")
def summary(body: GenerateIn):
    cached = _cached(body, "summary")
    if cached is not None:
        return {**cached, "cached": True}
    chunks = _chunks_for(body)
    if llm.configured_provider():
        text = llm.generate_text(
            "Summarise the study material below in clear paragraphs for a "
            "student revising for an exam. Use only this material.\n\n"
            + _context(chunks)
        )
        if text:
            return _store(body, "summary",
                          {"summary": text, "mode": "llm",
                           "sources": sorted({c["page"] for c in chunks})})
    text = " ".join(c["text"] for c in chunks[:3])
    return _store(body, "summary",
                  {"summary": text[:1200], "mode": "extractive_scaffold",
                   "sources": sorted({c["page"] for c in chunks[:3]})})


@router.post("/flashcards")
def flashcards(body: GenerateIn):
    cached = _cached(body, "flashcards")
    if cached is not None:
        return {**cached, "cached": True}
    chunks = _chunks_for(body)
    cards = None
    mode = "extractive_scaffold"
    if llm.configured_provider():
        raw = llm.generate_text(
            f"Create {body.count} flashcards from the study material below. "
            "Reply with ONLY a JSON array of objects with keys \"front\" "
            "(a question or prompt) and \"back\" (the answer). Use only "
            "this material.\n\n" + _context(chunks)
        )
        parsed = _parse_json(raw)
        if isinstance(parsed, list) and parsed and \
                all(isinstance(c, dict) and "front" in c and "back" in c
                    for c in parsed):
            cards = [{"front": str(c["front"]), "back": str(c["back"])}
                     for c in parsed[: body.count]]
            mode = "llm"
    if cards is None:
        cards = [{"front": "Explain: " + s[:80] + "...", "back": s}
                 for s in _sentences(chunks)[: body.count]]
    saved = get_repository().save_flashcards(
        body.workspace_id, body.document_id, cards)
    return _store(body, "flashcards", {"flashcards": saved, "mode": mode})


@router.get("/flashcards/due")
def due_flashcards(workspace_id: str | None = None,
                   document_id: str | None = None):
    repo = get_repository()
    if workspace_id and not repo.get_workspace(workspace_id):
        raise HTTPException(404, "Workspace not found")
    due = repo.list_due_flashcards(workspace_id, document_id)
    return {"flashcards": due, "count": len(due)}


@router.post("/flashcards/review")
def review_flashcard(body: ReviewIn):
    repo = get_repository()
    card = repo.get_flashcard(body.flashcard_id)
    if card is None:
        raise HTTPException(404, "Flashcard not found")
    state = srs.review(card, body.grade)
    updated = repo.update_flashcard_review(body.flashcard_id, state)
    return {"flashcard": updated}


@router.post("/quiz")
def quiz(body: GenerateIn):
    cached = _cached(body, "quiz")
    if cached is not None:
        return {**cached, "cached": True}
    chunks = _chunks_for(body)
    source_texts = [c["text"] for c in chunks]
    if llm.configured_provider():
        prompt = (
            f"Create {body.count} multiple-choice questions from the study "
            "material below. Reply with ONLY a JSON array of objects with "
            "keys \"question\", \"options\" (array of 4 strings) and "
            "\"answer\" (the exact correct option string). Use only this "
            "material.\n\n" + _context(chunks)
        )
        # One retry: a first response whose items all fail validation
        # (wrong option count, duplicates, ungrounded) is regenerated
        # once before falling back to the scaffold.
        for _attempt in range(2):
            items = _parse_json(llm.generate_text(prompt))
            valid, _rejected = quiz_validation.validate_quiz(
                items, source_texts)
            if valid:
                return _store(body, "quiz",
                              {"quiz": valid[: body.count], "mode": "llm"})
    questions = [{"question": "Which statement from your notes is correct?",
                  "options": [s], "answer": s,
                  "note": "Scaffold quiz - MCQ distractors arrive with LLM generation"}
                 for s in _sentences(chunks)[: body.count]]
    return _store(body, "quiz",
                  {"quiz": questions, "mode": "extractive_scaffold"})
